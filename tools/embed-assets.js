// Turn a static web site into gzipped C++ arrays the firmware serves with gizmo::handleEmbeddedAssetRequest
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { gzipSync } from 'node:zlib';

// Number of bytes on each line of the generated arrays
const BYTES_PER_LINE = 32;

// Content types by file extension
const CONTENT_TYPES = new Map([
	['.html', 'text/html; charset=utf-8'],
	['.js', 'application/javascript; charset=utf-8'],
	['.mjs', 'application/javascript; charset=utf-8'],
	['.css', 'text/css; charset=utf-8'],
	['.json', 'application/json; charset=utf-8'],
	['.webmanifest', 'application/manifest+json'],
	['.svg', 'image/svg+xml'],
	['.png', 'image/png'],
	['.jpg', 'image/jpeg'],
	['.jpeg', 'image/jpeg'],
	['.webp', 'image/webp'],
	['.ico', 'image/x-icon'],
	['.txt', 'text/plain; charset=utf-8'],
	['.woff', 'font/woff'],
	['.woff2', 'font/woff2']
]);

// Collect every file of a folder, recursively
const collectFiles = directoryPath => {
	const entries = readdirSync(directoryPath, { withFileTypes: true });

	// Flatten the folder tree into a list of file paths
	return entries.flatMap(entry => {
		const fullPath = path.join(directoryPath, entry.name);
		if (entry.isDirectory()) return collectFiles(fullPath);
		if (entry.isFile()) return [fullPath];
		return [];
	});
};

// Get the route a file is served at ("index.html" files are served at their folder)
export const getRoutePath = relativePath => {
	const normalizedPath = relativePath.split(path.sep).join('/');

	// Serve the index pages at their folder
	if (normalizedPath === 'index.html') return '/';
	if (normalizedPath.endsWith('/index.html')) return `/${normalizedPath.slice(0, -'/index.html'.length)}`;

	// Serve every other file at its own path
	return `/${normalizedPath}`;
};

// Get the content type of a file from its extension
export const getContentType = filePath => {
	const extension = path.extname(filePath).toLowerCase();
	return CONTENT_TYPES.get(extension) ?? 'application/octet-stream';
};

// Escape a text for a C++ string literal
const escapeCppString = value => {
	return value.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
};

// Format bytes as C++ hex literals, a fixed number per line
const formatByteLines = buffer => {
	const lines = [];

	// Split the bytes into lines
	for (let start = 0; start < buffer.length; start += BYTES_PER_LINE) {
		const bytes = Array.from(buffer.subarray(start, start + BYTES_PER_LINE), byte => `0x${byte.toString(16).padStart(2, '0')}`);
		lines.push(`\t${bytes.join(', ')},`);
	}

	// Return the lines
	return lines.join('\n');
};

// Build the asset list of a static site folder (sorted by path, so the output is stable)
export const buildAssets = siteDirectory => {
	if (!statSync(siteDirectory, { throwIfNoEntry: false })?.isDirectory()) {
		throw new Error(`Static site not found at ${siteDirectory}`);
	}

	// Collect and sort the files
	const files = collectFiles(siteDirectory).sort((left, right) => left.localeCompare(right));

	// Gzip every file and work out its route
	return files.map((filePath, index) => {
		const relativePath = path.relative(siteDirectory, filePath);
		return {
			symbolName: `embeddedAsset${index}`,
			sourcePath: relativePath.split(path.sep).join('/'),
			routePath: getRoutePath(relativePath),
			contentType: getContentType(filePath),
			contents: gzipSync(readFileSync(filePath), { level: 9 })
		};
	});
};

// Build the generated header, which declares the asset list
export const buildHeader = () => {
	return [
		'// Generated by gizmo-embed from the web app build: don\'t edit',
		'#ifndef GENERATED_ASSETS_H',
		'#define GENERATED_ASSETS_H',
		'',
		'#include <gizmo/embedded_assets.h>',
		'',
		'// Files of the web app, gzipped',
		'extern const gizmo::EmbeddedAsset EMBEDDED_ASSETS[];',
		'',
		'// Number of files of the web app',
		'extern const size_t EMBEDDED_ASSET_COUNT;',
		'',
		'#endif'
	].join('\n');
};

// Build the generated source, which holds the gzipped files
export const buildSource = assets => {
	// Define one array per file
	const arrays = assets.flatMap(asset => [
		`// ${asset.sourcePath}`,
		`static const uint8_t ${asset.symbolName}[] PROGMEM = {`,
		formatByteLines(asset.contents),
		'};',
		''
	]);

	// List the files with their routes
	const entries = assets.map(asset => `\t{ "${escapeCppString(asset.routePath)}", "${escapeCppString(asset.contentType)}", ${asset.symbolName}, sizeof(${asset.symbolName}) },`);

	// Return the whole source
	return [
		'// Generated by gizmo-embed from the web app build: don\'t edit',
		'#include "generated_assets.h"',
		'',
		'#include <pgmspace.h>',
		'',
		...arrays,
		'// Files of the web app, gzipped',
		'const gizmo::EmbeddedAsset EMBEDDED_ASSETS[] = {',
		...entries,
		'};',
		'',
		'// Number of files of the web app',
		'const size_t EMBEDDED_ASSET_COUNT = sizeof(EMBEDDED_ASSETS) / sizeof(EMBEDDED_ASSETS[0]);'
	].join('\n');
};